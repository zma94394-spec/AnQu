/**
 * ============================================================================
 *  改枪码的可复制性判据（**全站唯一实现**）
 *
 *  为什么单独成一个文件：显示侧（卡片 / 详情页的复制按钮）与提交侧
 *  （`lib/validation.ts` 的表单校验）问的其实是同一个问题 ——
 *  "这串字符是不是一条合法的改枪码"。两处各写一份正则，就会漂移成
 *  "提交时允许、复制时禁用"或反之，而那正是用户最无法理解的一类错。
 *
 *  口径来源（三者必须一致，改动要同时核对）：
 *   - 后端 `src/schemas/builds.schema.ts` 的 `CODE_PATTERN`
 *   - 数据库 `db/01_schema.sql` 的 `builds_code_len`（8~2048）
 *     与 `builds_code_no_space`（不得含任何空白）
 *   - 本文件
 *
 *  ⚠️ **判据不许"顺手放宽"**：一条含空格或中文的码，游戏客户端本来就读不懂。
 *  把复制按钮点亮只是把一个必然失败的操作交到用户手里，
 *  而且那还会让"复制保留原始字符"这条承诺变成谎话。
 * ============================================================================
 */

/** 可打印 ASCII（不含任何空白），长度 8~2048。与后端 `CODE_PATTERN` 逐字符相同。 */
export const BUILD_CODE_PATTERN = /^[\x21-\x7E]{8,2048}$/;

/**
 * 这串码能不能复制。
 *
 * 注意这里**不做 trim**：判据要评价的是"即将被写进剪贴板的那串字节"，
 * 而不是"我以为它长什么样"。一条首尾带空格的码就是不合法，
 * 该做的是禁用复制并说明原因，不是替用户偷偷改。
 */
export function isCopyableCode(code: string | null | undefined): boolean {
  return typeof code === 'string' && BUILD_CODE_PATTERN.test(code);
}

/** 不可复制时对用户说的那句话。文案只有一份，卡片与详情页不能各写一版。 */
export const UNCOPYABLE_CODE_HINT = '这条改枪码格式不完整，暂不可复制，请在游戏内核对后重新投稿';
